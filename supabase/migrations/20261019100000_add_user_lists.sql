-- Personal lists: three system lists ("À lire", "En pause", "Terminé") plus free custom lists.
-- Lists and their items are private: every row is owned by auth.uid() and protected by RLS.

create table if not exists public.user_lists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  kind text not null default 'custom' check (kind in ('to_read', 'on_hold', 'completed', 'custom')),
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);

create unique index if not exists user_lists_system_kind_uidx
on public.user_lists (user_id, kind) where kind <> 'custom';

create unique index if not exists user_lists_name_uidx
on public.user_lists (user_id, lower(btrim(name)));

create index if not exists user_lists_user_position_idx
on public.user_lists (user_id, position, id);

drop trigger if exists user_lists_set_updated_at on public.user_lists;
create trigger user_lists_set_updated_at
before update on public.user_lists
for each row execute function public.set_updated_at();

create table if not exists public.user_list_items (
  id bigint generated by default as identity primary key,
  list_id bigint not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  canonical_manga_id bigint not null references public.mangas(id) on delete cascade,
  position integer not null default 0,
  note text check (note is null or char_length(note) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (list_id, canonical_manga_id),
  -- An item can only live in a list owned by the same user.
  foreign key (list_id, user_id) references public.user_lists(id, user_id) on delete cascade
);

create index if not exists user_list_items_list_position_idx
on public.user_list_items (list_id, position, id);

create index if not exists user_list_items_user_manga_idx
on public.user_list_items (user_id, canonical_manga_id);

drop trigger if exists user_list_items_set_updated_at on public.user_list_items;
create trigger user_list_items_set_updated_at
before update on public.user_list_items
for each row execute function public.set_updated_at();

-- New items are appended at the end of their list.
create or replace function public.user_list_items_append_position()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  select coalesce(max(item.position) + 1, 0)
  into new.position
  from public.user_list_items item
  where item.list_id = new.list_id;
  return new;
end
$$;

drop trigger if exists user_list_items_append_position on public.user_list_items;
create trigger user_list_items_append_position
before insert on public.user_list_items
for each row execute function public.user_list_items_append_position();

alter table public.user_lists enable row level security;
alter table public.user_list_items enable row level security;

revoke all on public.user_lists from anon, authenticated;
revoke all on public.user_list_items from anon, authenticated;
grant select, insert, delete on public.user_lists to authenticated;
grant update (name, position) on public.user_lists to authenticated;
grant select, insert, delete on public.user_list_items to authenticated;
grant update (note, position) on public.user_list_items to authenticated;

create policy "Lists are visible to their owner"
on public.user_lists for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Custom lists are created by their owner"
on public.user_lists for insert to authenticated
with check ((select auth.uid()) = user_id and kind = 'custom');

create policy "Lists are updated by their owner"
on public.user_lists for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Only custom lists are deleted by their owner"
on public.user_lists for delete to authenticated
using ((select auth.uid()) = user_id and kind = 'custom');

create policy "List items are visible to their owner"
on public.user_list_items for select to authenticated
using ((select auth.uid()) = user_id);

-- Checking list ownership here (not only through the foreign key) rejects foreign lists
-- before unique constraints run, so their contents cannot be probed.
create policy "List items are created by their owner"
on public.user_list_items for insert to authenticated
with check (
  (select auth.uid()) = user_id
  and exists (
    select 1 from public.user_lists list
    where list.id = list_id and list.user_id = (select auth.uid())
  )
);

create policy "List items are updated by their owner"
on public.user_list_items for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "List items are deleted by their owner"
on public.user_list_items for delete to authenticated
using ((select auth.uid()) = user_id);

-- System lists cannot be inserted through the insert policy, so this definer function
-- creates them for the calling user only. It is idempotent.
create or replace function public.ensure_default_user_lists()
returns setof public.user_lists
language plpgsql
security definer
set search_path = public
as $$
declare
  caller uuid := auth.uid();
begin
  if caller is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  insert into public.user_lists (user_id, name, kind, position)
  values
    (caller, 'À lire', 'to_read', 0),
    (caller, 'En pause', 'on_hold', 1),
    (caller, 'Terminé', 'completed', 2)
  on conflict do nothing;

  return query
  select list.*
  from public.user_lists list
  where list.user_id = caller
  order by list.position, list.id;
end
$$;

-- Rewrites positions from an ordered id array; RLS restricts it to the caller's rows.
create or replace function public.reorder_user_list_items(p_list_id bigint, p_item_ids bigint[])
returns void
language sql
security invoker
set search_path = public
as $$
  update public.user_list_items item
  set position = ordered.ordinality - 1
  from unnest(p_item_ids) with ordinality as ordered(id, ordinality)
  where item.id = ordered.id
    and item.list_id = p_list_id;
$$;

revoke all on function public.ensure_default_user_lists() from public, anon;
revoke all on function public.reorder_user_list_items(bigint, bigint[]) from public, anon;
grant execute on function public.ensure_default_user_lists() to authenticated;
grant execute on function public.reorder_user_list_items(bigint, bigint[]) to authenticated;
